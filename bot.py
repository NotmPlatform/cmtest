    labels = ["A", "B", "C", "D"]

    lines = [
        f"Профессия: {profession}",
        f"Вопрос {index + 1} из {TEST_SIZE}",
        "",
        question["question"],
        "",
    ]

    for label, option_index in zip(labels, option_order):
        lines.append(f"{label}. {question['options'][option_index]}")

    return "\n".join(lines)


