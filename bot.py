def format_certificate_date(dt=None):
    dt = dt or datetime.now()
    months = [
        "January", "February", "March", "April", "May", "June",
        "July", "August", "September", "October", "November", "December",
    ]
    return f"{dt.day:02d} {months[dt.month - 1]} {dt.year}"


