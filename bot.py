def validate_question_bank():
    """Проверяет банк при запуске и останавливает бота при ошибке контента."""
    errors = []

    for profession_key, questions in QUESTION_BANK.items():
        if len(questions) < TEST_SIZE:
            errors.append(
                f"{profession_key}: в банке {len(questions)} вопросов, нужно минимум {TEST_SIZE}"
            )

        seen_questions = set()
        for index, question in enumerate(questions, start=1):
            text = str(question.get("question", "")).strip()
            options = question.get("options")
            correct = question.get("correct")

            if not text:
                errors.append(f"{profession_key} #{index}: пустой текст вопроса")
            elif text.casefold() in seen_questions:
                errors.append(f"{profession_key} #{index}: дубликат вопроса")
            else:
                seen_questions.add(text.casefold())

            if not isinstance(options, list) or len(options) != 4:
                errors.append(f"{profession_key} #{index}: должно быть ровно 4 варианта")
                continue

            normalized_options = [str(option).strip().casefold() for option in options]
            if any(not option for option in normalized_options):
                errors.append(f"{profession_key} #{index}: найден пустой вариант")
            if len(set(normalized_options)) != len(normalized_options):
                errors.append(f"{profession_key} #{index}: варианты должны быть уникальными")
            if not isinstance(correct, int) or not 0 <= correct < len(options):
                errors.append(f"{profession_key} #{index}: неверный индекс correct")

    if sum(BD_TEST_BLUEPRINT.values()) != TEST_SIZE:
        errors.append("BD_TEST_BLUEPRINT: сумма квот должна совпадать с TEST_SIZE")

    bd_questions = QUESTION_BANK.get("bd", [])
    category_counts = {}
    correct_positions = [0, 0, 0, 0]
    correct_is_longest = 0
    correct_is_shortest = 0

    for index, question in enumerate(bd_questions, start=1):
        category = question.get("category")
        category_counts[category] = category_counts.get(category, 0) + 1

        correct = question.get("correct")
        options = question.get("options")
        if isinstance(correct, int) and isinstance(options, list) and 0 <= correct < len(options):
            correct_positions[correct] += 1
            correct_length = len(options[correct])
            if correct_length == max(len(option) for option in options):
                correct_is_longest += 1
            if correct_length == min(len(option) for option in options):
                correct_is_shortest += 1

    for category, required_count in BD_TEST_BLUEPRINT.items():
        available_count = category_counts.get(category, 0)
        if available_count < required_count:
            errors.append(
                f"bd/{category}: доступно {available_count}, требуется минимум {required_count}"
            )

    if correct_positions and max(correct_positions) - min(correct_positions) > 1:
        errors.append(f"bd: позиции правильных ответов распределены неравномерно: {correct_positions}")

    if bd_questions and correct_is_longest > len(bd_questions) * 0.4:
        errors.append(
            "bd: более чем в 40% вопросов правильный ответ самый длинный; "
            "это создаёт подсказку по стилю"
        )

    if bd_questions and correct_is_shortest > len(bd_questions) * 0.4:
        errors.append(
            "bd: более чем в 40% вопросов правильный ответ самый короткий; "
            "это создаёт подсказку по стилю"
        )

    if errors:
        raise ValueError("Ошибки QUESTION_BANK:\n- " + "\n- ".join(errors))


def select_question_ids(profession_key):
    questions = QUESTION_BANK[profession_key]

    if profession_key != "bd":
        return random.sample(range(len(questions)), TEST_SIZE)

    selected_ids = []
    for category, count in BD_TEST_BLUEPRINT.items():
        category_ids = [
            index
            for index, question in enumerate(questions)
            if question.get("category") == category
        ]
        selected_ids.extend(random.sample(category_ids, count))

    random.shuffle(selected_ids)
    return selected_ids


